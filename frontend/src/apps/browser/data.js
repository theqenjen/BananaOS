export const SEARCH_SUGGESTIONS = ['banana bread recipe', 'rooftop orchard', 'night bus library', 'banana store', 'wiki banana'];

export function searchSites(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const words = q.split(/\s+/);
  return SEARCH_INDEX.map((entry) => {
    const haystack = `${entry.title} ${entry.snippet} ${entry.tags.join(' ')}`.toLowerCase();
    let score = 0;
    for (const word of words) {
      if (haystack.includes(word)) score += 1;
      if (entry.tags.includes(word)) score += 1;
      if (entry.title.toLowerCase().includes(word)) score += 1;
    }
    return { entry, score };
  })
    .filter((hit) => hit.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((hit) => hit.entry);
}
